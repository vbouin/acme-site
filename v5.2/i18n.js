(function i18nInit() {
  const STORAGE_KEY = 'acme-lang';
  const getLang = () => localStorage.getItem(STORAGE_KEY) || (navigator.language.startsWith('en') ? 'en' : 'fr');

  function apply(lang) {
    const dict = window.I18N[lang] || window.I18N.fr;
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        const attr = el.getAttribute('data-i18n-attr');
        if (attr) el.setAttribute(attr, dict[key]);
        else el.innerHTML = dict[key];
      }
    });
    document.querySelectorAll('.lang-toggle [data-lang]').forEach(b => {
      b.classList.toggle('active', b.dataset.lang === lang);
    });
    localStorage.setItem(STORAGE_KEY, lang);
    window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
  }

  window.setLanguage = apply;
  window.getLanguage = getLang;

  document.addEventListener('click', (e) => {
    const btn = e.target.closest('.lang-toggle [data-lang]');
    if (btn) {
      e.preventDefault();
      apply(btn.dataset.lang);
    }
  });

  document.addEventListener('DOMContentLoaded', () => apply(getLang()));
})();
